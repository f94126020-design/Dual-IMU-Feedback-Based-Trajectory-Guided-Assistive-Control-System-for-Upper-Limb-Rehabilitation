h(doc, "摘要")
para(doc, "穿戴式生醫電子若要長時間應用於復健輔具、人機介面或居家照護，除了辨識準確率，還必須兼顧訊號可靠度、即時性與能源消耗。表面肌電（sEMG）可在肢體產生明顯位移前反映肌肉活化，但容易受到電極位移、皮膚接觸、肌肉疲勞與動作偽影影響；慣性量測單元（IMU）可提供較穩定的動作學資訊，卻通常要在動作發生後才能觀察到明顯變化。既有研究已證明 sEMG 與慣性感測融合能改善動作辨識 [1–2]，也分別探討跨次量測變異 [3–4]、自適應取樣 [5–6] 與低功耗硬體辨識 [7–8]，但較少在同一個穿戴式系統中，將即時訊號品質、感測融合與硬體運算負擔共同納入設計。本研究擬建立同步 IMU–sEMG 穿戴式量測平台，從電極接觸、訊號飽和、工頻干擾、基線漂移及 IMU 動作偽影建立可解釋的訊號品質指標，據此動態調整多模態融合權重與系統運作模式。完成演算法驗證後，再進行定點化、記憶體與運算排程分析，部署於低功耗 MCU 或 FPGA，評估辨識 F1-score、動作起始延遲、跨次穩定度、記憶體、運算量與單次推論能耗，建立可向生醫訊號處理 IC 與穿戴式感測系統延伸的硬體架構。")

h(doc, "一、研究動機與個人基礎")
para(doc, "穿戴式生醫系統真正困難之處，並不是在乾淨資料上取得一次高準確率，而是感測器被日常使用者重複穿戴、移動與長時間操作後，仍能判斷目前資料是否可信。sEMG 的振幅微弱，電極位置或接觸狀況稍有改變，就可能造成特徵分布與辨識結果漂移；若系統仍以固定模型與固定運算模式處理，不僅容易產生錯誤判斷，也會持續消耗穿戴裝置有限的電力。相反地，若裝置能先辨識訊號品質，再決定應信任哪一種感測資訊、需要多少運算精度以及何時進入完整辨識模式，便可能同時提高可靠度與能源效率。這正是從生醫訊號演算法走向實際穿戴電子時必須補上的環節。")
para(doc, "我目前就讀生物醫學工程學系四年級，曾在雙 IMU 上肢輔助系統專題中參與感測、Raspberry Pi 軟體、ESP32 韌體、馬達控制、通訊與安全狀態機整合。實作經驗使我理解，訊號處理方法若忽略取樣同步、封包遺失、運算延遲與硬體限制，即使離線分析表現良好，也不一定能成為可靠的即時系統。長期而言，我希望朝韌體工程師與嵌入式系統開發方向發展，尤其關注感測器介面、即時資料流、通訊協定、定點運算、資源管理及故障處理。因此，本研究不只追求辨識準確率，也將演算法能否在資源受限硬體上穩定執行視為核心問題；並希望延續既有的 IMU 與嵌入式基礎，補強 sEMG、生醫類比前端及低功耗軟硬體協同設計，建立從微弱生理訊號擷取、品質判斷、意圖辨識到嵌入式實現的完整能力。")

h(doc, "二、文獻現況與研究缺口")
h(doc, "2.1 IMU 與 sEMG 具有互補性", 2)
para(doc, "研究顯示，肌電與慣性感測的共同使用可改善義肢或上肢動作辨識，因為 sEMG 描述肌肉活化，慣性感測則描述實際肢體姿態與運動 [1]。多模態穿戴式系統也已證明，有限數量的 IMU 與 sEMG 可共同追蹤上肢運動學與肌肉活動 [2]。因此，本研究採用兩種感測器並非任意疊加，而是利用兩者在動作發生前後、電生理與運動學上的互補資訊。")
h(doc, "2.2 日常穿戴造成的分布漂移仍是主要問題", 2)
para(doc, "sEMG 動作辨識在跨日、重複穿戴、電極位移、疲勞與個體差異下容易衰退；相關回顧指出，這些因素會增加使用者反覆校正的負擔 [3]。實驗研究亦顯示，電極位移會改變特徵與分類表現 [4]。相較於只增加模型複雜度，本研究希望先估測資料品質與異常來源，讓系統能降低不可信通道的權重、要求重新校正，或退回較保守的輸出。")
h(doc, "2.3 低功耗研究多集中於取樣或推論的單一環節", 2)
para(doc, "自適應取樣研究已證明，可依資料內容調整取樣頻率，在辨識效能與能源間取得平衡 [5]；非均勻生醫訊號取樣亦可減少 EMG、ECG、EEG 與加速度資料的取樣及傳輸負擔 [6]。另一方面，sEMG 的二值化神經網路已可在 FPGA 上完成低延遲推論 [7]，輕量化 sEMG 加速器也顯示定點化與專用資料路徑的可行性 [8]。然而，訊號品質判斷、感測融合和硬體工作量通常分開最佳化，尚缺乏由同一個品質指標共同驅動融合策略與運算模式的系統性比較。")

