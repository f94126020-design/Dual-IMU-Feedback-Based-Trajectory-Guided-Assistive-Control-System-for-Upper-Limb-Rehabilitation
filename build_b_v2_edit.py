h(doc, "四、研究方法")
h(doc, "4.1 穿戴式感測與類比前端", 2)
para(doc, "以一至兩顆 IMU 搭配雙通道或多通道 sEMG 為基本配置。第一階段使用商用生醫訊號前端或開發板，完成電極保護、儀表放大、帶通／陷波、ADC、共同時間戳與封包序號；同時記錄前端增益、飽和、電極脫落與雜訊狀態。類比前端以輸入雜訊、共模拒斥、頻寬、增益、動態範圍及功耗作為規格分析，不在研究計畫階段承諾自行完成晶片流片。若進入具 IC 設計條件的實驗室，再依量測結果設計可程式化增益、低功耗濾波或事件偵測電路。")
h(doc, "4.2 訊號品質與前處理", 2)
para(doc, "sEMG 先進行去直流、帶通／陷波、整流或時域特徵擷取，候選品質指標包含飽和比例、基線漂移、50／60 Hz 能量比、訊號變異、通道一致性與電極接觸狀態；IMU 則檢查加速度模長、角速度突變、姿態濾波殘差、時間戳與封包完整性。品質分數先採歸一化特徵與明確門檻，並以人工加入或實際產生的異常資料驗證；若資料量充足，再比較輕量統計分類器。")
h(doc, "4.3 多模態動作意圖辨識", 2)
para(doc, "任務先限定為上肢靜止、屈曲、伸展與數種基本動作，不一次追求大量手勢。基準方法包括閾值法、IMU-only、sEMG-only、固定 early／late fusion，以及 LDA、SVM 或輕量神經網路。主方法依兩種感測器的品質分數調整特徵或決策權重；若任一模態長時間不可信，則輸出低信心、要求重新校正或暫停控制。以滑動視窗進行線上推論，分別計算動作起始偵測延遲與穩態分類效能。")
h(doc, "4.4 嵌入式韌體與低功耗運作架構", 2)
para(doc, "先在 MCU 建立可量測的即時韌體基準，將感測器驅動、共同時間戳、DMA／中斷取樣、環形緩衝區、前處理、特徵擷取、融合、分類與通訊拆分為明確模組，記錄各階段執行時間、記憶體與資料遺失。低活動狀態僅維持必要的品質監測與低成本特徵；偵測到肌肉或動作活動後，再啟動完整取樣與融合。接著比較 8、12、16 位定點格式，決定乘加器、緩衝記憶體與資料路徑規格；若具 FPGA 平台，優先硬體化重複性高的濾波、視窗、特徵與矩陣運算。")
h(doc, "4.5 韌體可靠性與軟硬體協同驗證", 2)
para(doc, "以 PC 浮點結果作功能參考，逐步比較 MCU 浮點、MCU 定點與 FPGA 加速版本。除辨識效能外，韌體層將測試感測器逾時、封包遺失、緩衝區溢位、資料過期與模組重啟，並透過 watchdog、錯誤碼、狀態機及資料有效性旗標建立可追蹤的故障處理流程。量測端到端延遲、最壞執行時間、排程抖動、記憶體、平均功率與單次推論能耗，確認低功耗模式與錯誤恢復不會遺失重要的肌肉啟動資訊。最後形成取樣率、ADC 解析度、運算字長、緩衝容量、吞吐率與韌體介面等規格，作為後續穿戴式產品或生醫訊號處理硬體的設計依據。")

